// Sigle de couche → famille et clé de la bibliothèque tunisienne. Un sigle
// inconnu est traité comme un sol de même clé ; l'ESU n'a pas de critère.
const MATERIAUX = {
  BBSG: ["bitumineux", "BBSG"], GB2: ["bitumineux", "GB2"], GB3: ["bitumineux", "GB3"],
  EME2: ["bitumineux", "EME2"], GNT: ["sol", "GNT"], GCt3: ["hydraulique", "GCt3"],
  "STLH-T1-F": ["hydraulique", "STLH-T1-F"], "STLH-T1-G": ["hydraulique", "STLH-T1-G"],
  "STLH-T2-F": ["hydraulique", "STLH-T2-F"], "STLH-T2-G": ["hydraulique", "STLH-T2-G"],
  BC5: ["hydraulique", "BC5"], BC5g: ["hydraulique", "BC5g"], BC2: ["hydraulique", "BC2"],
  BC3: ["hydraulique", "BC3"], BAC: ["hydraulique", "BAC"], ESU: [null, "ESU"],
};
const PAR_SIGLE = new Map(Object.entries(MATERIAUX).map(([k, v]) => [k.toLowerCase(), v]));

const couches = (spec) => spec.split("/").map((t) => t.trim()).filter(Boolean).map((t) => {
  const [nature, ep] = t.split(":");
  const [famille, materiau] = PAR_SIGLE.get(nature.trim().toLowerCase()) ?? ["sol", nature.trim()];
  return { nature: nature.trim(), epCm: parseFloat(ep), famille, materiau, interface: null };
});

